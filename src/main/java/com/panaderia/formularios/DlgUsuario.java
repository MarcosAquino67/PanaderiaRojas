    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed

        String nombre = txtNombre.getText().trim();
        String cedula = txtDocumento.getText().trim();
        String contrasena = new String(txtContrasena.getPassword());
        String rol = (String) cmbRol.getSelectedItem();

        if (nombre.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Debe ingresar el nombre completo.", "Atención", javax.swing.JOptionPane.WARNING_MESSAGE);
            txtNombre.requestFocus();
            return;
        }
        if (cedula.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Debe ingresar la cédula.", "Atención", javax.swing.JOptionPane.WARNING_MESSAGE);
            txtDocumento.requestFocus();
            return;
        }
        if (contrasena.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Debe ingresar la contraseña.", "Atención", javax.swing.JOptionPane.WARNING_MESSAGE);
            txtContrasena.requestFocus();
            return;
        }

        boolean guardado = new CUsuarios().guardarUsuario(nombre, cedula, contrasena, rol, SEXO_POR_DEFECTO, CIUDAD_POR_DEFECTO);
        if (guardado) {
            javax.swing.JOptionPane.showMessageDialog(this, "Usuario registrado correctamente.", "Éxito", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            this.dispose();
        } else {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "No se pudo registrar el usuario (la cédula podría ya estar registrada).",
                    "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

