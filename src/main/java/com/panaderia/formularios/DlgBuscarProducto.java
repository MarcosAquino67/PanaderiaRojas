    private void buscarProductos() {
        DefaultTableModel modelo = (DefaultTableModel) tablaProductos.getModel();
        modelo.setRowCount(0);

        String busqueda = txtBuscar.getText().trim();
        String sql = "SELECT id_producto, nombre, precio, stock_actual FROM producto "
                   + "WHERE nombre LIKE ? OR CAST(id_producto AS CHAR) LIKE ? ORDER BY id_producto DESC";

        try (Connection con = CConexion.establecerConexion();
             PreparedStatement ps = con.prepareStatement(sql)) {

            ps.setString(1, "%" + busqueda + "%");
            ps.setString(2, "%" + busqueda + "%");

            try (ResultSet rs = ps.executeQuery()) {
                java.text.NumberFormat fmt = java.text.NumberFormat.getInstance(new java.util.Locale("es", "PY"));
                while (rs.next()) {
                    modelo.addRow(new Object[]{
                        rs.getInt("id_producto"),
                        rs.getString("nombre"),
                        fmt.format(rs.getDouble("precio")),
                        rs.getInt("stock_actual")
                    });
                }
            }
        } catch (SQLException e) {
            System.err.println("Error al buscar productos: " + e.getMessage());
        }
    }

    private void agregarProducto() {
        int fila = tablaProductos.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione un producto de la lista.", "Atención", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int idProducto = Integer.parseInt(tablaProductos.getValueAt(fila, 0).toString());
        String nombre = tablaProductos.getValueAt(fila, 1).toString();
        double precio = Double.parseDouble(tablaProductos.getValueAt(fila, 2).toString().replaceAll("[^0-9]", ""));
        int stock = Integer.parseInt(tablaProductos.getValueAt(fila, 3).toString().replaceAll("[^0-9]", ""));
        int cantidad = ((Number) spnCantidad.getValue()).intValue();
        int porcentajeIva = cbxIva.getSelectedIndex() == 0 ? 10 : 5;

        if (cantidad > stock) {
            JOptionPane.showMessageDialog(this,
                    "Stock insuficiente. Disponible: " + stock,
                    "Sin Stock", JOptionPane.WARNING_MESSAGE);
            return;
        }

        vistaVentas.agregarProductoACarrito(idProducto, nombre, cantidad, precio, porcentajeIva);
        dispose();
    }

