    public DlgCierreCaja(Frame parent, boolean modal) {
        super(parent, modal);
        initComponents();

        idCaja = new CCaja().obtenerCajaAbierta(Sesion.idUsuario > 0 ? Sesion.idUsuario : 1);
        if (idCaja == 0) {
            JOptionPane.showMessageDialog(parent,
                    "No hay una caja abierta para cerrar. Abra la caja desde el módulo Ventas.",
                    "Cierre de Caja", JOptionPane.WARNING_MESSAGE);
            dispose();
            return;
        }

        Object[] resumen = new CCaja().obtenerResumenCaja(idCaja);
        montoInicial = resumen[1] == null ? 0 : (Double) resumen[1];
        ventasEfectivo = new CCaja().obtenerVentasEfectivo(idCaja);
        ventasDelDia = new CCaja().obtenerVentasDelDia(idCaja);

        cargarResumen(resumen);
        initDatos();
        setLocationRelativeTo(parent);
    }

    private void cargarResumen(Object[] resumen) {
        lblFechaVal.setText(resumen[0] != null
                ? resumen[0].toString().replace(" ", "  ")
                : "-");
        lblMontoInicialVal.setText("₲ " + fmtPY.format(montoInicial));
        lblVentasEfectivoVal.setText("₲ " + fmtPY.format(ventasEfectivo));
        lblVentasDiaVal.setText("₲ " + fmtPY.format(ventasDelDia));
        lblEsperadoVal.setText("₲ " + fmtPY.format(montoInicial + ventasDelDia));
    }

    private void initDatos() {
        DecimalFormatSymbols simbolos = new DecimalFormatSymbols(Locale.GERMAN);
        DecimalFormat formatoGuarani = new DecimalFormat("#,##0", simbolos);

        SpinnerNumberModel model = new SpinnerNumberModel(0L, 0L, 100000000000L, 5000L);
        txtMontoFinal.setModel(model);
        JSpinner.NumberEditor editor = new JSpinner.NumberEditor(txtMontoFinal, "#,##0");
        txtMontoFinal.setEditor(editor);

        JTextField ftf = editor.getTextField();
        ftf.setFont(new Font("Segoe UI", Font.BOLD, 16));
        ftf.setHorizontalAlignment(JTextField.RIGHT);
        ftf.addKeyListener(new java.awt.event.KeyAdapter() {
            @Override
            public void keyReleased(java.awt.event.KeyEvent evt) {
                if (evt.getKeyCode() == java.awt.event.KeyEvent.VK_LEFT
                        || evt.getKeyCode() == java.awt.event.KeyEvent.VK_RIGHT) {
                    return;
                }
                SwingUtilities.invokeLater(() -> {
                    try {
                        String textoLimpio = ftf.getText().replaceAll("[^0-9]", "");
                        if (textoLimpio.isEmpty()) {
                            ftf.setText("");
                            txtMontoFinal.setValue(0L);
                        } else {
                            long valor = Long.parseLong(textoLimpio);
                            String textoFormateado = formatoGuarani.format(valor);
                            if (!ftf.getText().equals(textoFormateado)) {
                                ftf.setText(textoFormateado);
                                txtMontoFinal.setValue(valor);
                            }
                        }
                    } catch (NumberFormatException ex) {
                        // ignora entradas inválidas temporales
                    }
                });
            }
        });
    }

