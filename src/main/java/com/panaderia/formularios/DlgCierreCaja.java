    private void confirmarCierre() {
        double montoFinalReal;
        try {
            JSpinner.DefaultEditor ed = (JSpinner.DefaultEditor) txtMontoFinal.getEditor();
            String texto = ed.getTextField().getText().replaceAll("[^0-9]", "").trim();
            montoFinalReal = texto.isEmpty() ? 0 : Double.parseDouble(texto);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Ingrese un monto válido.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        boolean exito = new CCaja().cerrarCaja(idCaja, montoInicial, ventasDelDia, montoFinalReal);
        if (exito) {
            JOptionPane.showMessageDialog(this, "Caja cerrada correctamente.");
            dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Ocurrió un error al cerrar la caja.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

