    private void cargarConfiguracion() {
        Object[] cfg = new CConfiguracion().obtenerConfigTicket();
        txtNombreNegocio.setText(cfg[0] != null ? cfg[0].toString() : "");
        txtDireccion.setText(cfg[1] != null ? cfg[1].toString() : "");
        txtTelefono.setText(cfg[2] != null ? cfg[2].toString() : "");
        txtMensajePie.setText(cfg[3] != null ? cfg[3].toString() : "");
    }

    private void guardar() {
        String nombre = txtNombreNegocio.getText().trim();
        if (nombre.isEmpty()) {
            JOptionPane.showMessageDialog(this, "El nombre del negocio es obligatorio.", "Atención", JOptionPane.WARNING_MESSAGE);
            txtNombreNegocio.requestFocus();
            return;
        }

        boolean exito = new CConfiguracion().guardarConfigTicket(
                nombre,
                txtDireccion.getText().trim(),
                txtTelefono.getText().trim(),
                txtMensajePie.getText().trim());

        if (exito) {
            JOptionPane.showMessageDialog(this, "Configuración guardada correctamente.");
            dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Ocurrió un error al guardar la configuración.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

