    private void initDatos() {
        DecimalFormatSymbols simbolos = new DecimalFormatSymbols(Locale.GERMAN);
        DecimalFormat formatoGuarani = new DecimalFormat("#,##0", simbolos);

        SpinnerNumberModel model = new SpinnerNumberModel(0L, 0L, 100000000L, 5000L);
        txtMontoInicial.setModel(model);

        JSpinner.NumberEditor editor = new JSpinner.NumberEditor(txtMontoInicial, "#,##0");
        JFormattedTextField ftf = editor.getTextField();

        ftf.addKeyListener(new java.awt.event.KeyAdapter() {
            @Override
            public void keyReleased(java.awt.event.KeyEvent evt) {
                // Evita interferir con las teclas de navegación izquierda/derecha
                if (evt.getKeyCode() == java.awt.event.KeyEvent.VK_LEFT
                        || evt.getKeyCode() == java.awt.event.KeyEvent.VK_RIGHT) {
                    return;
                }

                SwingUtilities.invokeLater(() -> {
                    try {
                        String textoLimpio = ftf.getText().replaceAll("[^0-9]", "");

                        if (textoLimpio.isEmpty()) {
                            ftf.setText("");
                            txtMontoInicial.setValue(0L);
                        } else {
                            long valor = Long.parseLong(textoLimpio);
                            String textoFormateado = formatoGuarani.format(valor);

                            if (!ftf.getText().equals(textoFormateado)) {
                                ftf.setText(textoFormateado);
                                txtMontoInicial.setValue(valor);
                            }
                        }
                    } catch (NumberFormatException ex) {
                        // Previene errores por desbordamiento numérico
                    }
                });
            }
        });

        txtMontoInicial.setEditor(editor);
        ftf.setFont(new Font("Segoe UI", Font.BOLD, 16));
        ftf.setHorizontalAlignment(JTextField.RIGHT);
    }

