    private void confirmarApertura() {
        try {
            JSpinner.DefaultEditor editor = (JSpinner.DefaultEditor) txtMontoInicial.getEditor();
            String texto = editor.getTextField().getText().replaceAll("[^0-9]", "").trim();

            if (texto.isEmpty()) {
                montoInicial = 0.0;
            } else {
                montoInicial = Double.parseDouble(texto);
            }

            if (montoInicial < 0) {
                JOptionPane.showMessageDialog(this, "El monto no puede ser negativo.", "Atención", JOptionPane.WARNING_MESSAGE);
                return;
            }
            cajaAbierta = true;
            dispose();
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Ingrese un monto válido.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

