    /**
     * Calcula y carga el rango de fechas del período elegido en el combo.
     */
    private void aplicarPeriodo() {
        String[] rango = objetoReportes.calcularRango((String) cmbPeriodo.getSelectedItem());
        txtDesde.setText(rango[0]);
        txtHasta.setText(rango[1]);
        filtrarVentas();
    }

    private void filtrarVentas() {
        mostrandoMovimientos = false;
        String desde = txtDesde.getText().trim();
        String hasta = txtHasta.getText().trim();

        try {
            if (!desde.isEmpty()) {
                LocalDate.parse(desde);
            }
            if (!hasta.isEmpty()) {
                LocalDate.parse(hasta);
            }
        } catch (java.time.format.DateTimeParseException ex) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Formato de fecha inválido. Use yyyy-MM-dd (ej. 2026-09-11).",
                    "Fecha Incorrecta", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        objetoReportes.mostrarVentas(tablaReportes, desde, hasta);
        double[] totales = objetoReportes.obtenerTotales(desde, hasta);
        lblTotales.setText("  VENTAS DEL RANGO  |  Subtotal: ₲ " + fmtPY.format(totales[0])
                + "  |  IVA 5%: ₲ " + fmtPY.format(totales[1])
                + "  |  IVA 10%: ₲ " + fmtPY.format(totales[2]));
    }

