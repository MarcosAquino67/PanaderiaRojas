    private void btnCambiarPropiaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCambiarPropiaActionPerformed
        String actual = new String(txtActual.getPassword());
        String nueva = new String(txtNueva2.getPassword());
        String conf = new String(txtConf2.getPassword());

        if (actual.isEmpty() || nueva.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Complete todos los campos.", "Atención", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (!nueva.equals(conf)) {
            JOptionPane.showMessageDialog(this, "Las contraseñas no coinciden.", "Atención", JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (new CUsuarios().cambiarContrasenaPropia(Sesion.idUsuario, actual, nueva)) {
            JOptionPane.showMessageDialog(this, "Contraseña actualizada correctamente.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
            txtActual.setText("");
            txtNueva2.setText("");
            txtConf2.setText("");
        } else {
            JOptionPane.showMessageDialog(this, "La contraseña actual es incorrecta.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnCambiarPropiaActionPerformed

