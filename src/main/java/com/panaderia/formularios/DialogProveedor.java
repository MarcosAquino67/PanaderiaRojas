    private void cargarDepartamentos() {
        idsDepartamento.clear();
        cbxDepartamento.removeAllItems();
        String sql = "SELECT id_departamento, nombre_departamento FROM departamento ORDER BY nombre_departamento";
        try (Connection con = CConexion.establecerConexion();
             PreparedStatement ps = con.prepareStatement(sql);
             ResultSet rs = ps.executeQuery()) {
            while (rs.next()) {
                idsDepartamento.add(rs.getInt("id_departamento"));
                cbxDepartamento.addItem(rs.getString("nombre_departamento"));
            }
        } catch (SQLException e) {
            System.err.println("Error al cargar departamentos: " + e.getMessage());
        }
    }

    private int departamentoSeleccionado() {
        int idx = cbxDepartamento.getSelectedIndex();
        return (idx >= 0 && idx < idsDepartamento.size()) ? idsDepartamento.get(idx) : -1;
    }

    private void cargarCiudadesPorDepartamento() {
        idsCiudad.clear();
        cbxCiudad.removeAllItems();
        int idDep = departamentoSeleccionado();
        if (idDep == -1) {
            return;
        }
        String sql = "SELECT id_ciudad, nombre_ciudad FROM ciudad WHERE id_departamento = ? ORDER BY nombre_ciudad";
        try (Connection con = CConexion.establecerConexion();
             PreparedStatement ps = con.prepareStatement(sql)) {
            ps.setInt(1, idDep);
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    idsCiudad.add(rs.getInt("id_ciudad"));
                    cbxCiudad.addItem(rs.getString("nombre_ciudad"));
                }
            }
        } catch (SQLException e) {
            System.err.println("Error al cargar ciudades: " + e.getMessage());
        }
    }

    private void cargarDatos(int id) {
        setTitle("Modificar Proveedor");
        Object[] p = new CProveedores().obtenerProveedorPorId(id);
        if (p == null) {
            JOptionPane.showMessageDialog(this, "No se encontró el proveedor seleccionado.", "Error", JOptionPane.ERROR_MESSAGE);
            dispose();
            return;
        }

        txtRazonSocial.setText(p[1] != null ? p[1].toString() : "");
        txtRuc.setText(p[2] != null ? p[2].toString() : "");
        txtTelefono.setText(p[3] != null ? p[3].toString() : "");
        txtDireccion.setText(p[4] != null ? p[4].toString() : "");

        if (p[5] != null) {
            int idCiudad = ((Number) p[5]).intValue();
            seleccionarDepartamentoYCiudad(idCiudad);
        }
    }

    private void seleccionarDepartamentoYCiudad(int idCiudad) {
        int idDep = departamentoDeCiudad(idCiudad);
        if (idDep == -1) {
            return;
        }
        for (int i = 0; i < idsDepartamento.size(); i++) {
            if (idsDepartamento.get(i) == idDep) {
                cbxDepartamento.setSelectedIndex(i);
                break;
            }
        }
        cargarCiudadesPorDepartamento();
        for (int i = 0; i < idsCiudad.size(); i++) {
            if (idsCiudad.get(i) == idCiudad) {
                cbxCiudad.setSelectedIndex(i);
                break;
            }
        }
    }

    private int departamentoDeCiudad(int idCiudad) {
        String sql = "SELECT id_departamento FROM ciudad WHERE id_ciudad = ?";
        try (Connection con = CConexion.establecerConexion();
             PreparedStatement ps = con.prepareStatement(sql)) {
            ps.setInt(1, idCiudad);
            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    return rs.getInt("id_departamento");
                }
            }
        } catch (SQLException e) {
            System.err.println("Error al consultar departamento de ciudad: " + e.getMessage());
        }
        return -1;
    }

    private int ciudadSeleccionada() {
        int idx = cbxCiudad.getSelectedIndex();
        return (idx >= 0 && idx < idsCiudad.size()) ? idsCiudad.get(idx) : -1;
    }

    private void guardar() {
        String razonSocial = txtRazonSocial.getText().trim();
        String ruc = txtRuc.getText().trim();

        if (razonSocial.isEmpty()) {
            JOptionPane.showMessageDialog(this, "La razón social es obligatoria.", "Atención", JOptionPane.WARNING_MESSAGE);
            txtRazonSocial.requestFocus();
            return;
        }
        if (ruc.isEmpty()) {
            JOptionPane.showMessageDialog(this, "El RUC/Cédula es obligatorio.", "Atención", JOptionPane.WARNING_MESSAGE);
            txtRuc.requestFocus();
            return;
        }
        if (ciudadSeleccionada() == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione una ciudad.", "Atención", JOptionPane.WARNING_MESSAGE);
            return;
        }

        CProveedores dao = new CProveedores();
        boolean exito;
        if (idProveedor == -1) {
            exito = dao.guardarProveedor(razonSocial, ruc, txtTelefono.getText().trim(),
                    txtDireccion.getText().trim(), ciudadSeleccionada());
        } else {
            exito = dao.modificarProveedor(idProveedor, razonSocial, ruc, txtTelefono.getText().trim(),
                    txtDireccion.getText().trim(), ciudadSeleccionada());
        }

        if (exito) {
            JOptionPane.showMessageDialog(this, "Operación realizada con éxito.");
            dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Ocurrió un error al procesar el registro. Verifique que el RUC/Cédula no esté duplicado.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

